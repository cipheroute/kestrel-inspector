const STRINGS: Record<Lang, Record<StrKey, string>> = { en: STR_EN, ru: STR_RU };

function systemLang(): Lang {
  const ui = (chrome.i18n?.getUILanguage?.() || navigator.language || 'en').toLowerCase();
  return ui.startsWith('ru') ? 'ru' : 'en';
}

let currentLang: Lang = systemLang();

function t(key: StrKey): string {
  return STRINGS[currentLang][key];
}

// For strings used in one place only.
function tr(ru: string, en: string): string {
  return currentLang === 'ru' ? ru : en;
}
